def now():
    return datetime.now(timezone.utc).isoformat()


class Record(dict):
    """Support existing row['name'] and row[0] access patterns."""
    def __getitem__(self, key):
        if isinstance(key, int):
            return list(self.values())[key]
        return super().__getitem__(key)


class CursorAdapter:
    def __init__(self, cursor):
        self.cursor = cursor
        self.lastrowid = None

    def fetchone(self):
        row = self.cursor.fetchone()
        return Record(row) if row is not None else None

    def fetchall(self):
        return [Record(row) for row in self.cursor.fetchall()]

    def __iter__(self):
        for row in self.cursor:
            yield Record(row)


class ConnectionAdapter:
    def __init__(self, conn):
        self.conn = conn

    def __enter__(self):
        self.conn.__enter__()
        return self

    def __exit__(self, *args):
        return self.conn.__exit__(*args)

    def close(self):
        self.conn.close()

    def execute(self, sql, params=()):
        # Only static SQL from this application's own code is passed here.
        sql = sql.replace('?', '%s')
        if sql.startswith('INSERT OR IGNORE INTO users'):
            sql = sql.replace('INSERT OR IGNORE INTO users', 'INSERT INTO users') + ' ON CONFLICT (telegram_id) DO NOTHING'
        inserted_app = sql.lstrip().upper().startswith('INSERT INTO APPS(')
        if inserted_app:
            sql += ' RETURNING id'
        cursor = self.conn.execute(sql, params)
        result = CursorAdapter(cursor)
        if inserted_app:
            result.lastrowid = cursor.fetchone()['id']
        return result


def db():
    if not DATABASE_URL:
        raise RuntimeError('DATABASE_URL is missing in Render Environment')
    return ConnectionAdapter(psycopg.connect(DATABASE_URL, row_factory=dict_row, connect_timeout=10))


def init_db():
    with db() as conn:
        conn.execute('''CREATE TABLE IF NOT EXISTS users (
            telegram_id BIGINT PRIMARY KEY,
            username TEXT,
            created_at TEXT NOT NULL
        )''')
        conn.execute('''CREATE TABLE IF NOT EXISTS support_requests (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            telegram_id BIGINT NOT NULL,
            text TEXT NOT NULL,
            created_at TEXT NOT NULL
        )''')
        conn.execute('''CREATE TABLE IF NOT EXISTS apps (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name TEXT NOT NULL,
            description TEXT NOT NULL DEFAULT '',
            url TEXT NOT NULL,
            created_at TEXT NOT NULL,
            status TEXT NOT NULL DEFAULT 'published',
            photo_id TEXT,
            views BIGINT NOT NULL DEFAULT 0,
            clicks BIGINT NOT NULL DEFAULT 0
        )''')
        for column, definition in (
            ('status', "TEXT NOT NULL DEFAULT 'published'"),
            ('photo_id', 'TEXT'),
            ('views', 'BIGINT NOT NULL DEFAULT 0'),
            ('clicks', 'BIGINT NOT NULL DEFAULT 0'),
        ):
            conn.execute(f'ALTER TABLE apps ADD COLUMN IF NOT EXISTS {column} {definition}')


